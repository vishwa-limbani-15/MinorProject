"""
Hospital HRM Framework - Version 4
==================================

V4 adds the first trainable RL layer on top of the validated V3 environment.

Pipeline
--------
V2 skill-aware CP-SAT baseline
    -> V3 dynamic staff-level environment
    -> V4 PPO policy
    -> controlled evaluation against no-op baseline

Design choices
--------------
* The V3 environment remains the source of truth for operational validity.
* The PPO action space is a fixed candidate-index space of size
  ``max_candidates + 1``. Index 0 is no-op; remaining indices refer to the
  valid staff-level moves generated by V3 for the current state.
* Invalid/padded candidate indices are masked before action selection.
* The policy never directly edits the roster. It selects an action and V3
  validates/applies it.
* Training uses controlled stochastic events generated by V3.
* Evaluation uses paired scenarios: PPO and a no-op policy see the same
  initial baseline and the same forced events.

This remains a research/decision-support prototype, not a clinical production
system.
"""

